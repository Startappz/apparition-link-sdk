package com.startappz.apparition.user

import com.startappz.apparition.models.UserData
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow
import platform.Foundation.NSBundle
import platform.Foundation.NSLocale
import platform.Foundation.countryCode
import platform.Foundation.currentLocale
import platform.Foundation.languageCode
import platform.UIKit.UIDevice

internal actual fun generateUserData(): Flow<UserData> = flow {
    emit(
        UserData(
            appVersion = getAppVersion(),
            referrer = null,
            hardwareId = getDeviceId(),
            isHardwareIdAutoGenerated = false,
            phoneBrand = "Apple",
            phoneModel = UIDevice.currentDevice.model,
            osName = UIDevice.currentDevice.systemName,
            osVersion = UIDevice.currentDevice.systemVersion,
            apiLevel = 0,
            countryCode = NSLocale.currentLocale.countryCode ?: "NA",
            locale = NSLocale.currentLocale.languageCode,
            connectionType = getNetworkType(),
            carrier = null,
            adId = null
        )
    )
}

private fun getAppVersion(): String {
    val dictionary = NSBundle.mainBundle.infoDictionary
    val version = dictionary?.get("CFBundleShortVersionString") as? String
    return version ?: "Unknown"
}

fun getDeviceId(): String {
    val identifier = UIDevice.currentDevice.identifierForVendor
    return identifier?.UUIDString ?: "Unknown"
}

fun getNetworkType(): String {
//    Swift
