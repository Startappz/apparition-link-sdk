package com.startappz.apparition.user

import com.startappz.apparition.ApparitionLinkSDK
import com.startappz.apparition.data.ApPreferencesRepository
import com.startappz.apparition.models.UserData
import com.startappz.apparition.platform.isDebug
import com.startappz.apparition.referral.GoogleAdsId
import com.startappz.apparition.referral.GoogleInstallReferrers
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.flow.flow

internal actual fun generateUserData(): Flow<UserData> = flow {
    val context: PlatformContext = ApparitionLinkSDK.getPlatformContext()
    val deviceUtils = DeviceUtils(context)
    val screenInfo = deviceUtils.getScreenInfo()
    val networkInfo = NetworkInfo(context)
    val appUtils = AppUtils(context)
    val referrer = GoogleInstallReferrers(context).fetchInstallReferrer()
    val adId = GoogleAdsId.getGoogleAdvertisingId(context)
    val attributionLevel = ApPreferencesRepository.attributionLevel().first().value

    emit(
        UserData(
            appVersion = appUtils.getAppVersion(),
            referrer = referrer,
            hardwareId = deviceUtils.deviceId().first,
            isHardwareIdReal = deviceUtils.deviceId().second,
            phoneBrand = deviceUtils.getPhoneBrand(),
            phoneModel = deviceUtils.getPhoneModel(),
            osName = deviceUtils.getOperatingSystemName(),
            osVersion = deviceUtils.getOperatingSystemVersion(),
            apiLevel = deviceUtils.getOperatingSystemVersionReleaseNumber(),
            countryCode = deviceUtils.getDeviceCountryCode(),
            cpuType = deviceUtils.getDeviceCpuType(),
            locale = deviceUtils.getDeviceLocale(),
            connectionType = networkInfo.getConnectionType(),
            carrier = networkInfo.getCarrier(),
            //TODO: set the generated UUID for now
            adId = deviceUtils.getAnonymousAdId(),
            anonymousId = deviceUtils.getAnonymousAdId(),
            phoneScreenDpi = screenInfo.first,
            phoneScreenHeight = screenInfo.third,
            phoneScreenWidth = screenInfo.second,
            phoneMode = deviceUtils.uiMode(),
            localeIp = networkInfo.getIPAddress(),
            build = appUtils.getAppVersionCode(context).toString(),
            osVersionAndroid = deviceUtils.getOperatingSystemVersionReleaseNumber().toString(),
            debug = isDebug,
            update = System.currentTimeMillis(),
            userEnvironment = appUtils.getAppEnvironment(),
            apparitionRequestId = appUtils.getApparitionRequestId(),
            installReferrerExtras = "{}",
            latVal = attributionLevel,
            googleAdvertisingId = adId,
            installBrttVersion = appUtils.getBrrtVersion(),
            isWifi = networkInfo.isDeviceConnectedOnWifi()
        )
    )

}

data class InitRequest(
    val appVersion: String,
    val referrer: String, // who started the app
    val hardwareId: String, // try to fetch AndroidId, otherwise auto generated UUID and cache it
    val isHardwareIdAutoGenerated: Boolean, // true when auto generated
    val phoneBrand: String,
    val phoneModel: String,
    val osName: String,
    val osVersion: String,
    val apiLevel: Int,
    val countryCode: String, // iso 2
    val locale: String, // en-GB
    val connectionType: String, // wifi / mobile
    val carrier: String?
)